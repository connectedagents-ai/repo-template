LEGAL = re.compile(r"litigat|privilege|deposition|filing|case-|rico|evidence|damages|claims|contract|legal", re.I)


def cmd_import_agents(a):
    """Codex agent TOML (name, description, developer_instructions) -> agents/<name>/AGENT.md. Existing AGENT.md files are kept."""
    import tomllib
    made = kept = 0
    for p in sorted(a.source.glob("*.toml")):
        try:
            d = tomllib.loads(p.read_text())
        except (tomllib.TOMLDecodeError, UnicodeDecodeError) as e:
            print(f"skip {p.name}: {e}")
            continue
        agent_id = re.sub(r"[^a-z0-9-]+", "-", str(d.get("name") or p.stem).lower()).strip("-")
        dest = a.root / "agents" / agent_id / "AGENT.md"
        if dest.exists():
            kept += 1
            continue
        role = " ".join(str(d.get("description", "")).split()).replace(":", " -")[:200]
        ns = "core,privileged" if LEGAL.search(f"{agent_id} {role}") else "core,engineering"
        text = agent_md(agent_id, a.system, role or agent_id, "T2", ns).replace(
            "Follow AGENTS.md", f"Imported from {a.system}: {p.name}.\n\n{d.get('developer_instructions', '').strip()}\n\nFollow AGENTS.md")
        made += write(dest, text, a.apply)
        write(dest.parent / "receipts/.keep", "", a.apply, quiet=True)
    print(f"{'imported' if a.apply else 'would import'} {made} agents ({kept} already present)")


# ---------- memory import ----------
def parse_items(path):
    """Yield (body, key, extra) from JSONL records, Markdown bullets/lines or plain text lines."""
    text = path.read_text(errors="replace")
    if path.suffix == ".jsonl":
        for ln in text.splitlines():
            if ln.strip():
                r = json.loads(ln)
                body = r.get("body_md") or r.get("text") or r.get("content") or ""
                yield body.strip(), r.get("key"), r
        return
    for ln in text.splitlines():
        s = re.sub(r"^\s*(?:[-*+]|\d+[.)])\s+", "", ln).strip()
        if not s or s.startswith(("#", "<!--", "---")) or len(s) < 3:
            continue
        m = re.match(r"^\**([A-Za-z][\w /-]{1,40}?)\**:\s+(.+)$", s)
        yield s, (re.sub(r"\W+", "-", m.group(1).lower()).strip("-") if m else None), {}


def cmd_import(a):
    if a.namespace not in NAMESPACES:
        sys.exit(f"--namespace must be one of {NAMESPACES}")
    dest = a.root / "memory/sources" / a.platform / f"{a.account}.jsonl"
    existing = read_jsonl(dest)
    seen = {i["provenance_hash"] for i in existing}
    files = [p for x in a.inputs for p in ([x] if x.is_file() else sorted(x.rglob("*"))) if p.is_file()]
    new = []
    for f in files:
        stamp = datetime.datetime.fromtimestamp(f.stat().st_mtime, datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        item_type = "instruction" if re.search(r"instruction|agents\.md|claude\.md|gemini\.md|rules", f.name, re.I) else "memory"
        for body, key, r in parse_items(f):
            if not body:
                continue
            prov = h(f"{a.platform}|{a.account}|{norm(body)}", 32)
            if prov in seen:
                continue
            seen.add(prov)
            tags = sorted(set(r.get("tags") or []) | set(a.tag))
            new.append({"platform": a.platform, "account": a.account, "item_type": r.get("item_type", item_type),
                        "item_id": h(prov), "title": body[:80], "body_md": body,
                        "created_at": r.get("created_at", stamp), "updated_at": r.get("updated_at", stamp),
                        "tags": tags, "project": r.get("project", a.project), "source_url": r.get("source_url", str(f)),
                        "provenance_hash": prov, "namespace": r.get("namespace", a.namespace), "key": key})
    print(f"{len(new)} new items from {len(files)} files -> {dest} ({len(existing)} already there)")
    if new:
        write(dest, jsonl(existing + new), a.apply)


