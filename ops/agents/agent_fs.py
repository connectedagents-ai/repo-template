# ---------- sync ----------
def managed(existing, block, target):
    """Return the target's new text: one managed block (or one @import line for Claude), everything else untouched."""
    if target.endswith(".claude/CLAUDE.md"):
        line = f"@{block}"
        return existing if line in existing.splitlines() else existing.rstrip("\n") + ("\n\n" if existing.strip() else "") + line + "\n"
    new = f"{START}\n{block}\n{END}"
    if START in existing and END in existing:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: new, existing, flags=re.S)
    return existing.rstrip("\n") + ("\n\n" if existing.strip() else "") + new + "\n"


def cmd_sync(a):
    home = Path.home()
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = home / "Archive" / f"agent-home-sync-{stamp}"
    restore = []
    for tool, (fname, _, target) in TOOLS.items():
        src = a.root / "tools" / tool / fname
        if not src.exists():
            print(f"skip {tool}: run render first")
            continue
        if target is None:
            print(f"paste  {tool:<12} {src}")
            continue
        dest = home / target
        existing = dest.read_text() if dest.exists() else ""
        block = str(src.resolve()) if tool == "claude" else src.read_text().strip()
        new = managed(existing, block, target)
        if new == existing:
            print(f"ok     {tool:<12} {dest}")
            continue
        print(f"{'UPDATE' if a.apply else 'would update'} {tool:<12} {dest}")
        if a.apply:
            if dest.exists():
                (backup / target).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(dest, backup / target)
                restore.append(f'cp "{backup / target}" "{dest}"')
            else:
                restore.append(f'rm -f "{dest}"')
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(new)
    if restore:
        backup.mkdir(parents=True, exist_ok=True)
        (backup / "restore.sh").write_text("#!/bin/bash\nset -e\n" + "\n".join(restore) + "\n")
        print(f"backups + undo: bash {backup / 'restore.sh'}")
    elif not a.apply:
        print("DRY RUN. Re-run with --apply.")


