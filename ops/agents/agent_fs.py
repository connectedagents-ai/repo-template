    agents = load_agents(root)
    newest = max(e["updated_at"] for e in pack) if pack else "never"
    decisions = root / "chairman/principal_decisions.yaml"
    open_items = len(re.findall(r"\bOPEN\b", decisions.read_text())) if decisions.exists() else 0
    out = {}
    for ns in NAMESPACES:
        fs = facts(pack, [ns])
        out[root / f"memory/namespaces/{ns}.md"] = "\n".join([BANNER, f"# Memory: {ns}", f"{len(fs)} facts, newest {newest[:10]}", ""] +
                                                              ([bullet(e) for e in fs] or ["(empty)"])) + "\n"
        if ns in GENERAL:
            out[root / f"memory/SYSTEM_MEMORY_v1/{ns}.md"] = "\n".join(
                [BANNER, f"## SYSTEM_MEMORY_v1 · {ns}"] + [f"- {e['body_md']}" for e in fs]) + "\n"
    counts = " · ".join(f"{ns}: {len(facts(pack, [ns]))}" for ns in NAMESPACES)
    out[root / "memory/README.md"] = "\n".join([
        BANNER, "# Memory", "", f"Facts by namespace: {counts}. Last updated: {newest[:10]}.", "",
        "Lifecycle: export each account -> `agent_fs.py memory import` -> `memory merge` (dedupe, conflicts, boundary) -> `render` -> `sync`.",
        "Sources live in `sources/<platform>/<account>.jsonl`; `pack.jsonl` is the unified pack; read `CONFLICTS.md` and `BOUNDARY.md` after each merge.",
        "Restricted namespaces (family-office, privileged) hold pointers only; their content never enters a general-purpose tool.", ""]) + "\n"
    rows = []
    for folder, meta, body, receipts in agents:
        nss = ns_list(meta.get("memory_namespaces", "core"))
        fs = facts(pack, nss)
        out[folder / "memory/MEMORY.md"] = "\n".join([BANNER, f"# Memory for {meta.get('agent_id', folder.name)}",
                                                      f"Namespaces: {', '.join(nss)}", ""] + ([bullet(e) for e in fs] or ["(empty)"])) + "\n"
        last = receipts[-1] if receipts else "none yet"
        out[folder / "README.md"] = "\n".join([
            BANNER, f"# {meta.get('agent_id', folder.name)}", "", f"**Role:** {meta.get('role', '')}  ", f"**System:** {meta.get('system', '')}  ",
            f"**Risk tier:** {meta.get('risk_tier', '')}  ", f"**Memory:** {', '.join(nss)} ({len(fs)} facts, see memory/MEMORY.md)  ",
            f"**Skills:** {', '.join(ns_list(meta.get('skills', []))) or 'none'}  ", f"**Approval gates:** {', '.join(ns_list(meta.get('approval_gates', [])))}  ",
            f"**Last receipt:** {last}", "", "Instructions: AGENT.md."]) + "\n"
        rows.append(f"| [{folder.name}](agents/{folder.name}/README.md) | {meta.get('system', '')} | {meta.get('risk_tier', '')} | "
                    f"{', '.join(nss)} | {meta.get('role', '')} |")
