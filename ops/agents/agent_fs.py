# ---------- small helpers ----------
def write(path, text, apply, quiet=False):
    """Write only when content changes; report what (would) change."""
    old = path.read_text() if path.exists() else None
    if old == text:
        return False
    if not quiet:
        print(f"{'WRITE' if apply else 'would write'} {path}")
    if apply:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return True


def front_matter(text):
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        return {}, text
    meta = {}
    for ln in m.group(1).splitlines():
        k, sep, v = ln.partition(":")
        if sep:
            v = v.strip()
            meta[k.strip()] = [x.strip() for x in v[1:-1].split(",") if x.strip()] if v.startswith("[") else v
    return meta, m.group(2)


def norm(text):
    return re.sub(r"[^a-z0-9 ]", "", re.sub(r"\s+", " ", text.lower())).strip()


def h(text, n=16):
    return hashlib.sha256(text.encode()).hexdigest()[:n]


def read_jsonl(path):
    return [json.loads(ln) for ln in path.read_text().splitlines() if ln.strip()] if path.exists() else []


def jsonl(items):
    return "".join(json.dumps(i, sort_keys=True) + "\n" for i in items)


